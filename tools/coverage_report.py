"""Coverage check: can a person anywhere in the pilot districts reach help?

Usage: python coverage_report.py <data folder>  > COVERAGE.md
For every upazila it checks police / administration / health / fire / women & children / disaster,
and for every union the chairman, members, village police and union office.
Anything missing is shown with the fallback the website will use instead.
"""
import collections as C, json, os, sys, unicodedata

sys.stdout.reconfigure(encoding="utf-8")                        # the report is Bangla + emoji; works on Windows too
DATA = sys.argv[1] if len(sys.argv) > 1 else "."
norm = lambda s: unicodedata.normalize("NFC", s or "")           # Bangla letters come in two forms (BUILD_PLAN §3)


def load(name):
    with open(os.path.join(DATA, name), encoding="utf-8") as f:
        return json.load(f)


nat = load("national_hotlines.json")["records"]
UPAZILA_NEEDS = [("police", "Police station", "SP office (district police)"),
                 ("administration", "UNO / upazila administration", "DC office"),
                 ("health", "Upazila hospital", "District hospital / civil surgeon + 16263"),
                 ("fire", "Fire station", "District fire service + 102"),
                 ("women_children", "Women affairs officer", "District women affairs + 109"),
                 ("disaster", "PIO / disaster", "District relief office + 1090")]


def ok(n):
    return f"✅ {n}" if n else "⚠️ 0"


print("# SafeConnect – Coverage Report\n")
print("Generated by `tools/coverage_report.py`. ✅ = official numbers collected · ⚠️ = missing; the website uses the fallback shown.\n")
print("**Everywhere (national, always shown):** " + ", ".join(f"{r['numbers'][0]} {r['name_en']}" for r in nat[:9]) + " …\n")
total = C.Counter()
for fname in ("contacts_noakhali.json", "contacts_coxsbazar.json"):
    doc = load(fname)
    R = [r for r in doc["records"] if r["phones"]]
    dist = doc["district"]
    district_level = C.Counter(r["category"] for r in R if r["level"] in ("district", "regional"))
    print(f"\n## {dist}\n")
    print("**District level:** " + ", ".join(f"{k} {v}" for k, v in sorted(district_level.items())) + "\n")
    print("### Upazilas\n")
    print("| Upazila | " + " | ".join(n[1] for n in UPAZILA_NEEDS) + " | Municipality |")
    print("|---|" + "---|" * (len(UPAZILA_NEEDS) + 1))
    for upz in sorted({r["upazila_en"] for r in doc["records"] if r["upazila_en"]}):
        rs = [r for r in R if r["upazila_en"] == upz and r["level"] in ("upazila", "municipality")]
        cats = C.Counter(r["category"] for r in rs if r["level"] == "upazila")
        muni = sorted({r["municipality_bn"] for r in rs if r["level"] == "municipality"})
        cells = []
        for cat, _, fallback in UPAZILA_NEEDS:
            cells.append(ok(cats[cat]) if cats[cat] else f"⚠️ → {fallback}")
            total["upazila_" + cat + ("_ok" if cats[cat] else "_fallback")] += 1
        print(f"| {upz} | " + " | ".join(cells) + f" | {', '.join(muni) or '–'} |")
    print("\n### Unions\n")
    print("| Upazila | Union | Chairman / administrator | Members with number | Village police | Union office |")
    print("|---|---|---|---|---|---|")
    unions = {(u["upazila_en"], norm(u["union_bn"])): [] for u in doc["unions"]}
    for r in doc["records"]:
        if r["level"] == "union" and r["union_bn"]:
            unions.setdefault((r["upazila_en"], norm(r["union_bn"])), []).append(r)
    has = lambda r, words: r["phones"] and any(norm(w) in norm(r["designation_bn"]) for w in words)
    for (upz, un), rs in sorted(unions.items(), key=lambda x: (x[0][0] or "", x[0][1])):
        head = sum(1 for r in rs if has(r, ("চেয়ারম্যান", "প্রশাসক")))
        members = sum(1 for r in rs if has(r, ("মেম্বার", "সদস্য")))
        vp = sum(1 for r in rs if r["category"] == "village_police")
        office = sum(1 for r in rs if r["category"] == "union_office")
        for k, v in (("union_head", head), ("union_members", members), ("union_village_police", vp)):
            total[k + ("_ok" if v else "_missing")] += 1
        print(f"| {upz} | {un} | {ok(head)} | {ok(members)} | {ok(vp) if vp else '⚠️ → police station'} | {ok(office) if office else '–'} |")

print("\n## Summary\n")
for k in sorted(total):
    print(f"- {k.replace('_', ' ')}: {total[k]}")
